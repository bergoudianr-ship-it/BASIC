create or replace function public.fn_is_admin()
returns boolean
language sql stable security definer set search_path to 'public'
as $function$
  select exists (
    select 1 from public.usuarios u
    where u.email = lower(auth.jwt() ->> 'email') and u.role = 'admin' and u.ativo
  );
$function$;

-- Login por e-mail/senha (bcrypt via pgcrypto). Retorna vazio se inválido.
create or replace function public.fn_login_senha(p_email text, p_senha text)
returns table(email text, nome text, role text)
language plpgsql security definer set search_path to 'public', 'extensions'
as $function$
declare v record;
begin
  select u.* into v from public.usuarios u where u.email = lower(p_email) and u.ativo limit 1;
  if v is null or v.senha_hash is null then return; end if;
  if crypt(p_senha, v.senha_hash) <> v.senha_hash then return; end if;
  update public.usuarios set ultimo_acesso = now() where id = v.id;
  return query select v.email, v.nome, v.role;
end $function$;

-- Autocadastro (signup) — cria usuário 'membro' com senha própria.
create or replace function public.fn_criar_conta(p_email text, p_senha text, p_nome text default null::text)
returns text
language plpgsql security definer set search_path to 'public', 'extensions'
as $function$
begin
  if p_email is null or p_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then return 'EMAIL_INVALIDO'; end if;
  if coalesce(length(p_senha),0) < 6 then return 'SENHA_CURTA'; end if;
  if exists (select 1 from public.usuarios where email = lower(p_email)) then return 'DUPLICADO'; end if;
  insert into public.usuarios(nome, email, role, ativo, senha_hash)
    values (coalesce(nullif(p_nome,''), split_part(lower(p_email),'@',1)), lower(p_email), 'membro', true, crypt(p_senha, gen_salt('bf')));
  return 'OK';
exception when unique_violation then return 'DUPLICADO';
end $function$;

-- Verifica se um e-mail está liberado para logar (allowlist / status ativo).
create or replace function public.fn_login_permitido(p_email text)
returns table(permitido boolean, role text, nome text)
language sql stable security definer set search_path to 'public'
as $function$
  select true, u.role, u.nome
  from public.usuarios u
  where u.email = lower(p_email) and u.ativo
  limit 1;
$function$;

create or replace function public.fn_registrar_acesso()
returns void
language plpgsql security definer set search_path to 'public'
as $function$
begin
  update public.usuarios
    set ultimo_acesso = now()
    where email = lower(auth.jwt() ->> 'email');
end $function$;

-- ── Administração de usuários (chamadas pela aba Configurações, exigem admin) ──
create or replace function public.fn_acesso_listar(p_admin text)
returns setof usuarios
language sql security definer set search_path to 'public'
as $function$
  select u.* from public.usuarios u
  where exists (select 1 from public.usuarios a
                where a.email = lower(p_admin) and a.role = 'admin' and a.ativo)
  order by u.id;
$function$;

-- Overload 1: cria usuário já com senha definida pelo admin.
create or replace function public.fn_acesso_add(p_admin text, p_nome text, p_email text, p_senha text, p_role text)
returns text
language plpgsql security definer set search_path to 'public', 'extensions'
as $function$
begin
  if not exists (select 1 from public.usuarios a where a.email = lower(p_admin) and a.role='admin' and a.ativo)
    then return 'NAO_AUTORIZADO'; end if;
  if coalesce(length(p_senha),0) < 6 then return 'SENHA_CURTA'; end if;
  if coalesce(p_role,'membro') not in ('admin','membro') then p_role := 'membro'; end if;
  insert into public.usuarios(nome, email, role, ativo, criado_por, senha_hash)
    values (p_nome, lower(p_email), coalesce(p_role,'membro'), true, lower(p_admin), crypt(p_senha, gen_salt('bf')));
  return 'OK';
exception when unique_violation then return 'DUPLICADO';
end $function$;

-- Overload 2: cria usuário sem senha (define depois via fn_definir_senha).
create or replace function public.fn_acesso_add(p_admin text, p_nome text, p_email text, p_role text)
returns text
language plpgsql security definer set search_path to 'public'
as $function$
begin
  if not exists (select 1 from public.usuarios a where a.email = lower(p_admin) and a.role='admin' and a.ativo)
    then return 'NAO_AUTORIZADO'; end if;
  if coalesce(p_role,'membro') not in ('admin','membro') then p_role := 'membro'; end if;
  insert into public.usuarios(nome, email, role, ativo, criado_por)
    values (p_nome, lower(p_email), coalesce(p_role,'membro'), true, lower(p_admin));
  return 'OK';
exception when unique_violation then return 'DUPLICADO';
end $function$;

create or replace function public.fn_acesso_del(p_admin text, p_email text)
returns text
language plpgsql security definer set search_path to 'public'
as $function$
begin
  if not exists (select 1 from public.usuarios a where a.email = lower(p_admin) and a.role='admin' and a.ativo)
    then return 'NAO_AUTORIZADO'; end if;
  if lower(p_email) = lower(p_admin) then return 'PROPRIO'; end if;
  delete from public.usuarios where email = lower(p_email);
  return 'OK';
end $function$;

create or replace function public.fn_acesso_set_ativo(p_admin text, p_email text, p_ativo boolean)
returns text
language plpgsql security definer set search_path to 'public'
as $function$
begin
  if not exists (select 1 from public.usuarios a where a.email = lower(p_admin) and a.role='admin' and a.ativo)
    then return 'NAO_AUTORIZADO'; end if;
  update public.usuarios set ativo = p_ativo where email = lower(p_email);
  return 'OK';
end $function$;

create or replace function public.fn_definir_senha(p_admin text, p_email text, p_senha text)
returns text
language plpgsql security definer set search_path to 'public', 'extensions'
as $function$
begin
  if not exists (select 1 from public.usuarios a where a.email = lower(p_admin) and a.role='admin' and a.ativo)
    then return 'NAO_AUTORIZADO'; end if;
  if coalesce(length(p_senha),0) < 6 then return 'SENHA_CURTA'; end if;
  update public.usuarios set senha_hash = crypt(p_senha, gen_salt('bf')) where email = lower(p_email);
  return 'OK';
end $function$;

-- ── Persistência do estado do app na nuvem (por usuário) ───────────────────
create or replace function public.fn_estado_salvar(p_email text, p_chave text, p_valor jsonb)
returns void
language plpgsql security definer set search_path to 'public'
as $function$
begin
  if p_email is null or length(trim(p_email)) = 0 then raise exception 'email obrigatorio'; end if;
  insert into public.app_estado(email, chave, valor, atualizado_em)
  values (lower(trim(p_email)), p_chave, coalesce(p_valor,'{}'::jsonb), now())
  on conflict (email, chave) do update set valor = excluded.valor, atualizado_em = now();
end; $function$;

create or replace function public.fn_estado_carregar(p_email text)
returns table(chave text, valor jsonb, atualizado_em timestamptz)
language sql security definer set search_path to 'public'
as $function$
  select chave, valor, atualizado_em from public.app_estado where email = lower(trim(p_email));
$function$;

