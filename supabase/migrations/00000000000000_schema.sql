-- usuarios: cada usuário vê/edita a si mesmo; admin vê e gerencia todos.
create policy usuarios_select on public.usuarios for select to authenticated
  using (fn_is_admin() or email = lower(auth.jwt() ->> 'email'));
create policy usuarios_insert on public.usuarios for insert to authenticated
  with check (fn_is_admin());
create policy usuarios_update on public.usuarios for update to authenticated
  using (fn_is_admin()) with check (fn_is_admin());
create policy usuarios_delete on public.usuarios for delete to authenticated
  using (fn_is_admin() and email <> lower(auth.jwt() ->> 'email'));

-- app_estado: sem policy de tabela — todo acesso passa pelas RPCs
-- fn_estado_salvar / fn_estado_carregar (SECURITY DEFINER).

-- Dados de mercado (ONS/ANEEL/BBCE): leitura livre para autenticados,
-- escrita restrita a admin. Padrão idêntico em todas as tabelas abaixo.
do $$
declare t text;
begin
  foreach t in array array[
    'ipdo_ear','ipdo_ena','ipdo_cmo_pld','ipdo_carga','ipdo_geracao','ipdo_intercambio',
    'ipdo_curtailment','ipdo_resumo_diario','ipdo_noticias','ipdo_alertas','ipdo_analise_trader',
    'pld_forward','aneel_bandeiras','ons_restricoes','ons_pmo','acl_contratos'
  ] loop
    execute format('create policy %I_auth_select on public.%I for select to authenticated using (true);', t, t);
    execute format('create policy %I_admin_write on public.%I for all to authenticated using (fn_is_admin()) with check (fn_is_admin());', t, t);
  end loop;
end $$;
