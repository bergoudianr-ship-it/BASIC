-- =====================================================================
-- Tabela de rolamentos (base para peças revestidas de poliuretano)
-- Projeto Supabase: pboizjwwxcnajeuteivp
-- Dimensões de contorno ISO 15 / DIN 625 (d=furo, D=externo, B=largura, em mm)
-- ATENÇÃO: conferir no datasheet do fabricante antes de usar como critério
-- de aprovação/reprovação. O Ø externo final do rolamento REVESTIDO de PU
-- é específico de cada aplicação (a capa de poliuretano fica no diâmetro externo).
-- =====================================================================

create table if not exists public.rolamentos (
  id bigint generated always as identity primary key,
  designacao text not null unique,
  serie text not null,
  d_furo numeric not null,
  d_externo numeric not null,
  largura numeric not null,
  revestimento_pu boolean not null default true,
  fonte text not null default 'ISO 15 / DIN 625',
  created_at timestamptz not null default now()
);

alter table public.rolamentos enable row level security;

drop policy if exists "leitura publica rolamentos" on public.rolamentos;
create policy "leitura publica rolamentos" on public.rolamentos for select using (true);

